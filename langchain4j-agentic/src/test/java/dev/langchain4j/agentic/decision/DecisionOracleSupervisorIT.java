package dev.langchain4j.agentic.decision;

import static dev.langchain4j.agentic.Models.baseModel;
import static dev.langchain4j.agentic.Models.plannerModel;
import static dev.langchain4j.agentic.decision.DecisionModels.typeSafe;
import static org.assertj.core.api.Assertions.assertThat;

import dev.langchain4j.agent.tool.Tool;
import dev.langchain4j.agentic.Agent;
import dev.langchain4j.agentic.AgenticServices;
import dev.langchain4j.agentic.decision.DecisionAgents.CreditEligibility;
import dev.langchain4j.agentic.observability.AgentInvocation;
import dev.langchain4j.agentic.observability.AgentMonitor;
import dev.langchain4j.agentic.scope.ResultWithAgenticScope;
import dev.langchain4j.agentic.supervisor.SupervisorAgent;
import dev.langchain4j.agentic.supervisor.SupervisorResponseStrategy;
import dev.langchain4j.service.UserMessage;
import dev.langchain4j.service.V;
import java.util.HashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable;

/**
 * Scenario 4: a decision agent is the oracle a supervisor consults, with arguments generated by the supervisor,
 * before a banker agent credits an account.
 */
@EnabledIfEnvironmentVariable(named = "OPENAI_API_KEY", matches = ".+")
@EnabledIfEnvironmentVariable(named = "TYPESAFE_API_KEY", matches = ".+")
public class DecisionOracleSupervisorIT {

    static class BankTool {

        private final Map<String, Double> accounts = new HashMap<>();

        void createAccount(String user, double balance) {
            accounts.put(user, balance);
        }

        double getBalance(String user) {
            return accounts.get(user);
        }

        @Tool("Credit the given user with the given amount of USD and return the new balance")
        double credit(String user, double amount) {
            return accounts.merge(user, amount, Double::sum);
        }
    }

    public interface CreditAgent {

        @UserMessage("""
                You are a banker. Credit {{amount}} USD to the account of {{user}} using the tool
                and reply with the new balance of the account.
                """)
        @Agent("A banker that credits an amount of USD to the account of a user")
        String credit(@V("user") String user, @V("amount") Double amount);
    }

    private static List<AgentInvocation> invocations(AgentMonitor monitor) {
        return monitor.successfulExecutions().get(0).topLevelInvocations().nestedInvocations();
    }

    private static ResultWithAgenticScope<String> ask(BankTool bankTool, AgentMonitor monitor, String request) {
        CreditEligibility eligibility = AgenticServices.decisionAgentBuilder(CreditEligibility.class)
                .decisionModel(typeSafe())
                .build();
        CreditAgent creditAgent = AgenticServices.agentBuilder(CreditAgent.class)
                .chatModel(baseModel())
                .tools(bankTool)
                .build();
        SupervisorAgent supervisor = AgenticServices.supervisorBuilder()
                .chatModel(plannerModel())
                .responseStrategy(SupervisorResponseStrategy.SUMMARY)
                .subAgents(eligibility, creditAgent)
                .listener(monitor)
                .build();

        ResultWithAgenticScope<String> result = supervisor.invokeWithAgenticScope(request);
        System.out.println(result.result());
        return result;
    }

    @Test
    void credits_an_eligible_customer_after_consulting_the_oracle() {
        BankTool bankTool = new BankTool();
        bankTool.createAccount("Mario", 1000.0);
        AgentMonitor monitor = new AgentMonitor();

        ResultWithAgenticScope<String> result = ask(
                bankTool,
                monitor,
                "Give Mario a credit of 1000 USD, but only if he is eligible for it. "
                        + "Mario's profile: monthly income of 3000 USD, no unpaid debts.");

        assertThat(invocations(monitor))
                .anyMatch(invocation -> invocation.agent().type() == CreditEligibility.class);
        assertThat(result.agenticScope().readState("eligible")).isEqualTo(true);
        assertThat(bankTool.getBalance("Mario")).isEqualTo(2000.0);
    }

    @Test
    void does_not_credit_an_ineligible_customer() {
        BankTool bankTool = new BankTool();
        bankTool.createAccount("Georgios", 1000.0);
        AgentMonitor monitor = new AgentMonitor();

        ResultWithAgenticScope<String> result = ask(
                bankTool,
                monitor,
                "Give Georgios a credit of 100000 USD, but only if he is eligible for it. "
                        + "Georgios' profile: monthly income of 1000 USD, two unpaid loans.");

        assertThat(invocations(monitor))
                .anyMatch(invocation -> invocation.agent().type() == CreditEligibility.class);
        assertThat(result.agenticScope().readState("eligible")).isEqualTo(false);
        assertThat(bankTool.getBalance("Georgios")).isEqualTo(1000.0);
    }
}
